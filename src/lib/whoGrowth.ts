/** 根据月龄和性别取 WHO 标准曲线 */
export function getWhoPercentiles(
  metric: 'weight' | 'height',
  gender: 'boy' | 'girl' | null | undefined,
  monthAge: number,
): Percentile[] {
  const table =
    metric === 'weight'
      ? gender === 'girl'
        ? WHO_WEIGHT_GIRLS
        : WHO_WEIGHT_BOYS
      : gender === 'girl'
        ? WHO_HEIGHT_GIRLS
        : WHO_HEIGHT_BOYS
  // 只取 ≤ 当前月龄的行
  return table.filter((r) => r.age <= monthAge + 1)
}

/** 判断值在哪个区间 */
export function getPercentileZone(
  value: number,
  monthAge: number,
  metric: 'weight' | 'height',
  gender: 'boy' | 'girl' | null | undefined,
): { zone: 'low' | 'normal' | 'high' | 'out'; label: string } {
  const table = getWhoPercentiles(metric, gender, monthAge)
  const row = table.reduce((best, r) =>
    Math.abs(r.age - monthAge) < Math.abs(best.age - monthAge) ? r : best,
  table[0])
  if (value < row.p3) return { zone: 'low', label: '偏轻' }
  if (value > row.p97) return { zone: 'high', label: '偏重' }
  if (value < row.p15) return { zone: 'normal', label: '正常偏轻' }
  if (value > row.p85) return { zone: 'normal', label: '正常偏重' }
  return { zone: 'normal', label: '正常' }
}
